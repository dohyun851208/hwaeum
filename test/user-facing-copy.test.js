const assert = require("node:assert/strict")
const fs = require("node:fs")
const path = require("node:path")
const test = require("node:test")

const projectDir = path.resolve(__dirname, "..")

test("studio and gallery user-facing labels avoid leftover English section words", () => {
  const studio = fs.readFileSync(path.join(projectDir, "studio.html"), "utf8")
  const channel = fs.readFileSync(path.join(projectDir, "channel.html"), "utf8")
  const index = fs.readFileSync(path.join(projectDir, "index.html"), "utf8")
  const studioSource = fs.readFileSync(path.join(projectDir, "js", "studio.js"), "utf8")
  const channelSource = fs.readFileSync(path.join(projectDir, "js", "channel.js"), "utf8")
  const shareStore = fs.readFileSync(path.join(projectDir, "js", "share-store.js"), "utf8")

  for (const html of [studio, channel, index]) {
    assert.doesNotMatch(html, />\s*(Step [1-5]|Atmosphere|Instrument|Student|Teacher|BGM|PIN)\s*</)
    assert.doesNotMatch(html, /placeholder="[^"]*(BGM|PIN)[^"]*"/)
    assert.doesNotMatch(html, /aria-label="[^"]*(BGM|PIN)[^"]*"/)
    assert.doesNotMatch(html, /<title>[^<]*(BGM|PIN)[^<]*<\/title>/)
  }

  assert.match(studio, />1단계</)
  assert.match(studio, />그림 선택하기</)
  assert.match(studio, />배경 음악 고르기</)
  assert.match(studio, />선율 그리기</)
  assert.match(studio, />작품 완성하기</)
  assert.match(studio, />화음 갤러리 입장하기</)
  assert.match(studio, />악기 미리 듣기</)
  assert.match(studio, /이 배경에 어울리는 악기 미리 듣기/)
  assert.doesNotMatch(studio, />배경\/악기</)
  assert.doesNotMatch(studio, />연주 악기</)
  assert.match(studio, />학생</)
  assert.match(studio, />선생님</)
  assert.match(studio, /화음 갤러리 들어가기/)
  assert.match(studio, /화음 갤러리 생성하기/)
  assert.match(studio, /관리자 번호 \(8624\)/)
  assert.match(studio, /번호 \(예 107\)/)
  assert.match(studio, /갤러리 이름 \(예: 여름 빛깔을 담은 노래\)/)
  assert.match(studio, /갤러리 코드 \(숫자 4자리 이상\)/)
  assert.doesNotMatch(studio, new RegExp("갤러리 " + "비밀" + "번호"))
  assert.match(studio, /관리자 번호\(8624\)로 화음 갤러리 생성이 가능하며/)
  assert.doesNotMatch(studio, /화음 갤러리 삭제/)
  assert.doesNotMatch(studio, new RegExp("화음 갤러리 " + "열기"))
  assert.doesNotMatch(studio, new RegExp("1차 " + "관리자 번호"))
  assert.doesNotMatch(studio, new RegExp("화음 갤러리 표시 " + "이름"))
  assert.doesNotMatch(studio, new RegExp("화음 갤러리 만들기 / " + "저장"))
  assert.match(index, /나만의 BGM 만들기/)
  assert.match(channel, /갤러리 코드/)
  assert.match(channel, /이름 변경/)
  assert.match(channel, /화음 갤러리 삭제하기/)
  assert.match(channel, /드로잉 이미지/)
  assert.match(channel, /작품 삭제/)
  assert.doesNotMatch(channel, /링크 복사/)
  assert.doesNotMatch(channel, /id="channelAdminPin"/)
  assert.doesNotMatch(channel, /id="channelNameInput"/)
  assert.doesNotMatch(channel, /id="channelNamePass"/)
  assert.match(channelSource, /관리자 번호를 입력하세요/)
  assert.match(channelSource, /바꿀 갤러리 이름을 입력하세요/)
  assert.doesNotMatch(channel, /어느 화음 갤러리에서든 작품을 지울 수 있어요/)
  assert.doesNotMatch(channel, /이름 저장은 관리자 번호와 갤러리 코드가 필요합니다/)
  assert.doesNotMatch(channel, new RegExp("갤러리 " + "비밀" + "번호"))
  assert.doesNotMatch(studioSource, /관리자 PIN/)
  assert.doesNotMatch(channelSource, /관리자 PIN/)
  assert.doesNotMatch(shareStore, /관리자 PIN이 필요/)
  assert.doesNotMatch(studioSource + channelSource + shareStore, new RegExp("갤러리 " + "비밀" + "번호|비" + "번"))
})
